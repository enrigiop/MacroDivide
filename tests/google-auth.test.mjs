import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=(await readFile(new URL('../member-auth.js',import.meta.url),'utf8')).replace(/^import .*;\n/,'');
const nodes=new Map();
const document={getElementById:id=>{if(!nodes.has(id))nodes.set(id,{style:{},disabled:false,textContent:''});return nodes.get(id)}};
let config,oauth,fail=false;
const sb={auth:{getSession:async()=>({data:{session:null}}),onAuthStateChange:()=>{},signInWithOAuth:async x=>{oauth=x;return {error:fail?new Error('Provider unavailable'):null}}}};
const context={createClient:(url,key,options)=>{config={url,key,options};return sb},document,location:{search:'',hash:''},URLSearchParams,setTimeout,fetch:()=>{throw Error('Signed-out user must not fetch protected app')}};
await vm.runInNewContext('(async()=>{'+source+'})()',context);
assert.equal(config.options.auth.flowType,'pkce');
assert.equal(nodes.get('auth').style.display,'block');
assert.equal(nodes.get('account').style.display,'none');
await nodes.get('google').onclick();
assert.equal(oauth.provider,'google');
assert.equal(oauth.options.redirectTo,'https://enrigiop.github.io/MacroDivide/app.html');
assert.equal(oauth.options.queryParams.prompt,'select_account');
assert.equal(oauth.options.queryParams.access_type,undefined);
fail=true;await nodes.get('google').onclick();
assert.equal(nodes.get('google').disabled,false);
assert.equal(nodes.get('message').textContent,'Provider unavailable');
console.log('Google auth checks passed: PKCE, redirect, signed-out gate, and recoverable provider errors.');
